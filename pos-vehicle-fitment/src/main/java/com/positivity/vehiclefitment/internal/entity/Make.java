package com.positivity.vehiclefitment.internal.entity;

import com.positivity.shared.id.UUIDv7Id;
import com.positivity.tenancy.TenantGlobal;
import jakarta.persistence.*;
import java.time.Instant;
import java.time.LocalDateTime;
import java.util.HashSet;
import java.util.Set;
import java.util.UUID;
import lombok.Data;
import lombok.EqualsAndHashCode;
import lombok.ToString;
import org.springframework.data.annotation.CreatedDate;
import org.springframework.data.annotation.LastModifiedDate;
import org.springframework.data.jpa.domain.support.AuditingEntityListener;

@Data
@Entity
@TenantGlobal(
        reason = "fitment reference data shared by every tenant (ADR-0062 section 5, db/tenancy-global-tables.txt)")
@EntityListeners(AuditingEntityListener.class)
@Table(name = "make")
public class Make {
    @Id
    @GeneratedValue
    @UUIDv7Id
    @Column(columnDefinition = "UUID")
    private UUID id;

    /**
     * vPIC's own numeric id for this row (#2416) — the id vPIC's dependent lookups take in their path.
     * {@code null} when the row did not come from vPIC (seeded, bulk-loaded, or created by a fitment
     * request); such a row cannot be refreshed from vPIC.
     */
    @Column(name = "nhtsa_id")
    private Long nhtsaId;

    private String name;

    /**
     * The manufacturers vPIC (or a fitment request) pairs this make with (#2453). A make is the brand and is
     * one row per vPIC Make_ID; several manufacturers can build it. Eager: the id list is part of the response.
     */
    @ManyToMany(fetch = FetchType.EAGER)
    @JoinTable(
            name = "make_manufacturer",
            joinColumns = @JoinColumn(name = "make_id"),
            inverseJoinColumns = @JoinColumn(name = "manufacturer_id"))
    @ToString.Exclude
    @EqualsAndHashCode.Exclude
    private Set<Manufacturer> manufacturers = new HashSet<>();

    private LocalDateTime cacheTimestamp;

    @CreatedDate
    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt;

    @LastModifiedDate
    @Column(name = "updated_at", nullable = false)
    private Instant updatedAt;

    /** Links the manufacturer if not already linked; returns whether a link was added. */
    public boolean linkManufacturer(Manufacturer manufacturer) {
        if (manufacturers.stream().anyMatch(m -> m.getId().equals(manufacturer.getId()))) {
            return false;
        }
        manufacturers.add(manufacturer);
        return true;
    }
    // Getters and setters are generated by Lombok's @Data annotation
}
