package com.positivity.inventory.internal.controller;

import com.positivity.events.EmitEvent;
import com.positivity.inventory.internal.dto.replenishment.CreateReplenishmentPolicyRequest;
import com.positivity.inventory.internal.dto.replenishment.ReplenishmentNeedResponse;
import com.positivity.inventory.internal.dto.replenishment.ReplenishmentPolicyResponse;
import com.positivity.inventory.internal.dto.replenishment.ReplenishmentScanResultResponse;
import com.positivity.inventory.internal.dto.replenishment.ReplenishmentTaskResponse;
import com.positivity.inventory.internal.dto.replenishment.SnoozeReplenishmentPolicyRequest;
import com.positivity.inventory.internal.dto.replenishment.UpdateReplenishmentPolicyRequest;
import com.positivity.inventory.internal.security.InventoryPermissionRegistry;
import com.positivity.inventory.service.ReplenishmentService;
import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.media.ArraySchema;
import io.swagger.v3.oas.annotations.media.Content;
import io.swagger.v3.oas.annotations.media.ExampleObject;
import io.swagger.v3.oas.annotations.media.Schema;
import io.swagger.v3.oas.annotations.responses.ApiResponse;
import io.swagger.v3.oas.annotations.tags.Tag;
import jakarta.validation.Valid;
import java.util.List;
import java.util.UUID;
import lombok.RequiredArgsConstructor;
import org.springframework.data.domain.Page;
import org.springframework.data.domain.Pageable;
import org.springframework.data.web.PageableDefault;
import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.security.access.prepost.PreAuthorize;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.PutMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RequestParam;
import org.springframework.web.bind.annotation.RestController;

@RestController
@RequestMapping("/v1/inventory/replenishment")
@RequiredArgsConstructor
@Tag(name = "Replenishment", description = "Replenishment task and policy endpoints")
public class ReplenishmentController {

    private final ReplenishmentService replenishmentService;

    @GetMapping("/tasks")
    @io.swagger.v3.oas.annotations.security.SecurityRequirement(
            name = "bearerAuth",
            scopes = {"inventory:on_hand:view"})
    @PreAuthorize("hasAuthority('inventory:on_hand:view')")
    @Operation(
            operationId = "listReplenishmentTasks",
            summary = "List replenishment tasks",
            description = """
                    Returns every open replenishment task — the pick-face restock work generated by the batch scan \
                    or the event-path evaluation.
                    Use this tool to see outstanding restock work; use listReplenishmentNeeds instead for a \
                    what-would-trigger report that also covers policies without tasks.
                    Preconditions: none; only tasks in open statuses are returned.
                    Required inputs: none; there is no request body, paging or filtering.
                    No events are emitted and no state changes; this is a read-only projection.
                    Returns 200 with an empty array when no tasks are open, so an empty result is not an error \
                    condition.
                    """,
            tags = {"Replenishment"})
    @ApiResponse(
            responseCode = "200",
            description = "Replenishment tasks returned",
            content =
                    @Content(
                            mediaType = "application/json",
                            array = @ArraySchema(schema = @Schema(implementation = ReplenishmentTaskResponse.class))))
    public ResponseEntity<List<ReplenishmentTaskResponse>> getReplenishmentTasks() {
        return ResponseEntity.ok(replenishmentService.getReplenishmentTasks());
    }

    @GetMapping("/policies")
    @io.swagger.v3.oas.annotations.security.SecurityRequirement(
            name = "bearerAuth",
            scopes = {"inventory:on_hand:view"})
    @PreAuthorize("hasAuthority('inventory:on_hand:view')")
    @Operation(
            operationId = "listReplenishmentPolicies",
            summary = "List replenishment policies",
            description = """
                    Lists configured replenishment policies as a page, optionally filtered to one location.
                    Use this tool to discover a policyId before updating or snoozing a policy; use \
                    listReplenishmentNeeds instead to see which policies would currently trigger.
                    Preconditions: none.
                    Required inputs: none; locationId is an optional query filter and the standard page/size \
                    parameters default to a page size of 20.
                    No events are emitted and no state changes; this is a read-only projection.
                    Returns 200 with an empty page when nothing is configured, so an empty result is not an error \
                    condition.
                    """,
            tags = {"Replenishment"})
    @ApiResponse(
            responseCode = "200",
            description = "Replenishment policies returned (paged)",
            content =
                    @Content(
                            mediaType = "application/json",
                            schema = @Schema(description = "Page of replenishment policies")))
    public ResponseEntity<Page<ReplenishmentPolicyResponse>> getReplenishmentPolicies(
            @io.swagger.v3.oas.annotations.Parameter(description = "Location identifier")
                    @RequestParam(required = false)
                    UUID locationId,
            @PageableDefault(size = 20) Pageable pageable) {
        return ResponseEntity.ok(replenishmentService.getReplenishmentPolicies(locationId, pageable));
    }

    @PostMapping("/policies")
    @EmitEvent(id = "INVENTORY_REPLENISHMENT_POLICY_CREATE", apiVersion = "1")
    @io.swagger.v3.oas.annotations.security.SecurityRequirement(
            name = "bearerAuth",
            scopes = {"inventory:replenishment:manage"})
    @PreAuthorize("hasAuthority('" + InventoryPermissionRegistry.REPLENISHMENT_MANAGE + "')")
    @Operation(
            operationId = "createReplenishmentPolicy",
            summary = "Create replenishment policy",
            description = """
                    Creates a min/max replenishment policy that drives orderpoint evaluation for one SKU at one \
                    location.
                    Use this tool to define when a pick face should be restocked; do not use \
                    updateReplenishmentPolicy, which retunes a policy that already exists.
                    Preconditions: none checked against existing state; a duplicate policy for the same SKU and \
                    location is not rejected here.
                    Required inputs: locationId (UUID), itemSKU, and minimumQuantity (at least 0) strictly less \
                    than maximumQuantity (at least 1); orderMultiple defaults to the vendor-feed pack size when one \
                    greater than 1 is known for a product-UUID SKU, preferredSourceType defaults to EITHER and \
                    active defaults to true.
                    Emits an INVENTORY_REPLENISHMENT_POLICY_CREATE event; no task is created until a scan or stock \
                    event triggers the policy.
                    Returns 400 when minimumQuantity is not less than maximumQuantity or a required field is \
                    missing.
                    """,
            tags = {"Replenishment"})
    @ApiResponse(
            responseCode = "201",
            description = "Replenishment policy created",
            content =
                    @Content(
                            mediaType = "application/json",
                            schema = @Schema(implementation = ReplenishmentPolicyResponse.class)))
    @ApiResponse(responseCode = "400", description = "Validation failure")
    public ResponseEntity<ReplenishmentPolicyResponse> createReplenishmentPolicy(
            @io.swagger.v3.oas.annotations.parameters.RequestBody(
                            description = "Min/max thresholds and tuning fields for one SKU at one location.",
                            required = true,
                            content =
                                    @Content(
                                            mediaType = "application/json",
                                            examples = @ExampleObject(name = "Pick-face min/max policy", value = """
                                                                    {"locationId":"018f0a1b-2c3d-7e4f-8a9b-0c1d2e3f4a01",
                                                                     "itemSKU":"SKU-10042","minimumQuantity":5,
                                                                     "maximumQuantity":50,"orderMultiple":6,
                                                                     "leadTimeDaysOverride":3,
                                                                     "preferredSourceType":"EITHER","active":true}
                                                                    """)))
                    @Valid
                    @RequestBody
                    CreateReplenishmentPolicyRequest request) {
        return ResponseEntity.status(HttpStatus.CREATED).body(replenishmentService.createReplenishmentPolicy(request));
    }

    @PutMapping("/policies/{policyId}")
    @EmitEvent(id = "INVENTORY_REPLENISHMENT_POLICY_UPDATE", apiVersion = "1")
    @io.swagger.v3.oas.annotations.security.SecurityRequirement(
            name = "bearerAuth",
            scopes = {"inventory:replenishment:manage"})
    @PreAuthorize("hasAuthority('" + InventoryPermissionRegistry.REPLENISHMENT_MANAGE + "')")
    @Operation(
            operationId = "updateReplenishmentPolicy",
            summary = "Update replenishment policy",
            description = """
                    Replaces every tunable field of a replenishment policy: min/max thresholds, order multiple, \
                    lead-time override, preferred source type and active flag.
                    Use this tool to retune an existing policy; do not use snoozeReplenishmentPolicy, which manages \
                    the snooze state this endpoint cannot touch, and do not use createReplenishmentPolicy, which \
                    defines a new policy.
                    Preconditions: the policy must exist; its location and SKU identity are immutable here.
                    Required inputs: policyId (UUID) path parameter plus minimumQuantity (at least 0) strictly less \
                    than maximumQuantity (at least 1); omitted optional fields are cleared or reset — orderMultiple \
                    and leadTimeDaysOverride to none, preferredSourceType to EITHER, active to true.
                    Emits an INVENTORY_REPLENISHMENT_POLICY_UPDATE event; the next scan or stock event evaluates \
                    the new thresholds.
                    Returns 404 when the policy does not exist, and 400 when minimumQuantity is not less than \
                    maximumQuantity.
                    """,
            tags = {"Replenishment"})
    @ApiResponse(
            responseCode = "200",
            description = "Replenishment policy updated",
            content =
                    @Content(
                            mediaType = "application/json",
                            schema = @Schema(implementation = ReplenishmentPolicyResponse.class)))
    @ApiResponse(responseCode = "400", description = "Validation failure")
    @ApiResponse(responseCode = "404", description = "Policy not found")
    public ResponseEntity<ReplenishmentPolicyResponse> updateReplenishmentPolicy(
            @io.swagger.v3.oas.annotations.Parameter(description = "Replenishment policy identifier") @PathVariable
                    UUID policyId,
            @io.swagger.v3.oas.annotations.parameters.RequestBody(
                            description = "Replacement values for every tunable field of the policy; omitted"
                                    + " optional fields are cleared or reset to defaults.",
                            required = true,
                            content =
                                    @Content(
                                            mediaType = "application/json",
                                            examples = @ExampleObject(name = "Retuned thresholds", value = """
                                                                    {"minimumQuantity":8,"maximumQuantity":60,
                                                                     "orderMultiple":6,
                                                                     "preferredSourceType":"PURCHASE","active":true}
                                                                    """)))
                    @Valid
                    @RequestBody
                    UpdateReplenishmentPolicyRequest request) {
        return ResponseEntity.ok(replenishmentService.updateReplenishmentPolicy(policyId, request));
    }

    @PostMapping("/policies/{policyId}/snooze")
    @EmitEvent(id = "INVENTORY_REPLENISHMENT_POLICY_SNOOZE", apiVersion = "1")
    @io.swagger.v3.oas.annotations.security.SecurityRequirement(
            name = "bearerAuth",
            scopes = {"inventory:replenishment:manage"})
    @PreAuthorize("hasAuthority('" + InventoryPermissionRegistry.REPLENISHMENT_MANAGE + "')")
    @Operation(
            operationId = "snoozeReplenishmentPolicy",
            summary = "Snooze or unsnooze a replenishment policy",
            description = """
                    Snoozes a replenishment policy so scan, event and needs evaluation all skip it until the given \
                    future instant, or clears an existing snooze.
                    Use this tool to silence a policy temporarily; do not use updateReplenishmentPolicy, which \
                    cannot touch snooze state, and prefer snoozing over clearing the active flag when the pause \
                    should expire on its own.
                    Preconditions: the policy must exist; a non-null snoozedUntil must lie in the future.
                    Required inputs: policyId (UUID) path parameter and a body whose optional snoozedUntil instant \
                    sets the snooze; a null snoozedUntil clears it — there is no separate unsnooze endpoint.
                    Emits an INVENTORY_REPLENISHMENT_POLICY_SNOOZE event; the policy is excluded from evaluation \
                    until the instant passes.
                    Returns 404 when the policy does not exist, and 422 with REPLENISHMENT_SNOOZE_NOT_IN_FUTURE \
                    when snoozedUntil is not in the future.
                    """,
            tags = {"Replenishment"})
    @ApiResponse(
            responseCode = "200",
            description = "Snooze state updated",
            content =
                    @Content(
                            mediaType = "application/json",
                            schema = @Schema(implementation = ReplenishmentPolicyResponse.class)))
    @ApiResponse(responseCode = "404", description = "Policy not found")
    @ApiResponse(responseCode = "422", description = "snoozedUntil is not in the future")
    public ResponseEntity<ReplenishmentPolicyResponse> snoozeReplenishmentPolicy(
            @io.swagger.v3.oas.annotations.Parameter(description = "Replenishment policy identifier") @PathVariable
                    UUID policyId,
            @io.swagger.v3.oas.annotations.parameters.RequestBody(
                            description = "Snooze instant to set, or a null snoozedUntil to clear the snooze.",
                            required = true,
                            content =
                                    @Content(
                                            mediaType = "application/json",
                                            examples =
                                                    @ExampleObject(
                                                            name = "Snooze for one week",
                                                            value = "{\"snoozedUntil\":\"2026-08-20T00:00:00Z\"}")))
                    @Valid
                    @RequestBody
                    SnoozeReplenishmentPolicyRequest request) {
        return ResponseEntity.ok(replenishmentService.snoozeReplenishmentPolicy(policyId, request.getSnoozedUntil()));
    }

    @GetMapping("/needs")
    @EmitEvent(id = "INVENTORY_REPLENISHMENT_NEEDS_LIST", apiVersion = "1")
    @io.swagger.v3.oas.annotations.security.SecurityRequirement(
            name = "bearerAuth",
            scopes = {"inventory:on_hand:view"})
    @PreAuthorize("hasAuthority('inventory:on_hand:view')")
    @Operation(
            operationId = "listReplenishmentNeeds",
            summary = "Replenishment needs report",
            description = """
                    Reports, for every active non-snoozed replenishment policy, the projected availability at its \
                    lead-time horizon, whether a scan would trigger, the multiple-rounded suggested quantity and \
                    the projected stock-out deadline.
                    Use this tool for ops review before materialising work; do not use runReplenishmentScan, which \
                    actually creates or refreshes tasks, and use listReplenishmentTasks instead to see tasks that \
                    already exist.
                    Preconditions: none; snoozed and inactive policies are silently excluded.
                    Required inputs: none; there is no request body or filtering.
                    Emits an INVENTORY_REPLENISHMENT_NEEDS_LIST event; the report itself never creates or \
                    refreshes tasks, and it shares the batch scan's math so it matches what a scan run at the same \
                    instant would do.
                    Returns 200 with an empty array when no policies qualify, so an empty result is not an error \
                    condition.
                    """,
            tags = {"Replenishment"})
    @ApiResponse(
            responseCode = "200",
            description = "Replenishment needs returned",
            content =
                    @Content(
                            mediaType = "application/json",
                            array = @ArraySchema(schema = @Schema(implementation = ReplenishmentNeedResponse.class))))
    public ResponseEntity<List<ReplenishmentNeedResponse>> getReplenishmentNeeds() {
        return ResponseEntity.ok(replenishmentService.getReplenishmentNeeds());
    }

    @PostMapping("/scan")
    @EmitEvent(id = "INVENTORY_REPLENISHMENT_SCAN_RUN", apiVersion = "1")
    @io.swagger.v3.oas.annotations.security.SecurityRequirement(
            name = "bearerAuth",
            scopes = {"inventory:replenishment:manage"})
    @PreAuthorize("hasAuthority('" + InventoryPermissionRegistry.REPLENISHMENT_MANAGE + "')")
    @Operation(
            operationId = "runReplenishmentScan",
            summary = "Run the batch replenishment scan",
            description = """
                    Runs the batch replenishment scan, evaluating every active non-snoozed policy against its \
                    lead-time forecast and creating or refreshing replenishment tasks for triggered pick faces.
                    Use this tool to materialise restock work; use listReplenishmentNeeds instead for a \
                    side-effect-free preview of what the scan would do.
                    Preconditions: none; policies preferring PURCHASE produce purchase suggestions instead of \
                    tasks, and a need already covered by an open source transfer order or an open task is not \
                    duplicated.
                    Required inputs: none; there is no request body.
                    Emits an INVENTORY_REPLENISHMENT_SCAN_RUN event and creates or refreshes tasks and purchase \
                    suggestions; the run is idempotent per policy and UTC day, and a triggered policy whose \
                    computed quantity is zero creates nothing.
                    Returns 200 with a summary of policies evaluated, tasks created and refreshed, suggestions \
                    created and refreshed, and policies skipped.
                    """,
            tags = {"Replenishment"})
    @ApiResponse(
            responseCode = "200",
            description = "Scan completed; summary returned",
            content =
                    @Content(
                            mediaType = "application/json",
                            schema = @Schema(implementation = ReplenishmentScanResultResponse.class)))
    public ResponseEntity<ReplenishmentScanResultResponse> runReplenishmentScan() {
        return ResponseEntity.ok(replenishmentService.runBatchReplenishmentScan());
    }
}
