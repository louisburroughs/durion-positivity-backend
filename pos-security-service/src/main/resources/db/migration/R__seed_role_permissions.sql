-- Repeatable seed: canonical role -> permission baseline (role_permissions).
--
-- WHY THIS FILE EXISTS
-- Authorities carried in a JWT are resolved from this table at login:
--     users -> user_roles -> roles -> role_permissions -> permissions
-- RoleAuthorityServiceImpl reads these rows; it no longer hardcodes role
-- expansion in Java. An empty role_permissions therefore means "no authority",
-- so this baseline must stay complete.
--
-- POLICY
-- * Least privilege for operational roles. Domain grants mirror a capability the
--   role already exercised through the retired hardcoded expansion, or (for
--   SYSTEM_ADMINISTRATOR and DISPATCHER, which the hardcoded switch never
--   covered) the role's documented job function.
-- * Assistant baseline: every role listed in section 3 receives mcp:chat:execute,
--   mcp:chat:stream, nlti:request:submit and nlti:request:read. These are the
--   conversational entrypoints. MCP now gates the order, pricing and catalog
--   facades on explicit domain permission codes rather than the synthetic
--   AUTHENTICATED tier; only domains that still lack a real permission code for
--   MCP to mirror remain on that floor.
--   NOTE this includes the customer-facing CUSTOMER and SELF_SERVICE_CUSTOMER
--   roles, which previously held nothing at all.
--   These are explicit grants, not a rule the database enforces: a role created
--   later through the role-permission admin API starts with NO grants, assistant
--   entrypoints included, until something grants them. To make a new role part of
--   the baseline, add it to section 3 here.
-- * SYSTEM_ADMINISTRATOR is deliberately NOT a superuser. It holds the
--   security/admin surface plus MCP administration (system prompts, LLM API
--   configuration, tool management, document ingest) and no accounting, catalog,
--   workorder, inventory or shop authority. ADMIN remains the all-domain role
--   and is a strict superset.
-- * The retired switch also expanded ACCOUNTANT, AP_CLERK, CONTROLLER, CSR,
--   FLEET_MANAGER and GL_ANALYST. Those are NOT reproduced here except
--   CONTROLLER (see the 2026-08 rescope bullet below): no migration and no
--   runtime initializer creates the remaining five, and both user_roles and
--   role_assignments are foreign-keyed to roles(id), so no user could hold one.
--   To make a persona real, create the role first, then grant it here.
-- * invoice:finalize:override (#1374) gates manager-approval elevation for
--   invoice finalization above the service-advisor cap. It is held by ADMIN
--   and the manager roles only — ACCOUNT_MANAGER, GENERAL_MANAGER,
--   LOCATION_MANAGER, MANAGER and SHOP_MANAGER — per the product decision on
--   that issue. Do not widen it: the permission exists specifically to cap
--   what a service advisor can finalize by naming an absent manager.
-- * workorder:workorder:delete (#1432) is a hard delete that destroys history,
--   so it is held by ADMIN and the manager roles only — GENERAL_MANAGER,
--   LOCATION_MANAGER, MANAGER and SHOP_MANAGER — mirroring the
--   invoice:finalize:override precedent. Advisors create workorders
--   (workorder:workorder:create) but cannot destroy them.
-- * SERVICE_ADVISOR holds the CRM onboarding surface (#1435, #1437):
--   crm:party:view/search/create, crm:person:read/create and
--   crm:vehicle:create (alongside its existing crm:vehicle:search/view), so a
--   walk-in customer can be looked up, duplicate-checked, onboarded and have
--   their vehicle registered at the counter. Deliberately NOT
--   crm:party:edit/deactivate/merge — corrections and destructive party
--   operations stay manager-and-above.
-- * INVENTORY_LEAD is the parts-receiving persona (#1439): it holds the
--   receiving surface (ASN, receiving sessions, goods receipts, cross-dock
--   issue, putaway, shortages, on-hand visibility) plus purchase-order
--   create/view. The elevated escape hatches stay out: goods_receipt:override
--   and the putaway capacity/compatibility overrides are not granted here.
-- * The inventory:availability:* and inventory:on_hand:* families answer two
--   different questions and neither implies the other (ADR-0057, #1494).
--   on_hand:* reads the stock record itself — counted quantity, lot and serial
--   detail, location contents, rollups. availability:* reads the derived
--   projection: on-hand net of prior commitments (allocations, reservations,
--   expired lots) plus the incoming/outgoing forecast, i.e. what can be
--   promised. Each family splits again on cross-location disclosure:
--   availability:read is the scope-limited answer, availability:search the
--   per-location breakdown that enumerates every location holding the SKU.
--   TECHNICIAN and SERVICE_ADVISOR hold :read so they can tell whether a part
--   can be committed to the job in front of them; they deliberately do NOT hold
--   :search or any on_hand code. Before #1494, availability:read was granted
--   here and enforced by no endpoint, so it granted nothing.
-- * order:purchase_order:approve and :transmit (#1438) are held by ADMIN and
--   the PO-approver personas LOCATION_MANAGER and INVENTORY_MANAGER only.
--   Note the legacy inventory:purchase_order:* family remains seeded
--   (ADMIN-only) although no controller enforces it — pos-order enforces
--   order:purchase_order:*; retiring the legacy family needs a versioned
--   migration and is tracked on #1438.
-- * The inventory adjustment roles (#1373) carry the documented model:
--   INVENTORY_LEAD creates and views adjustment requests;
--   INVENTORY_MANAGER and INVENTORY_CONTROLLER additionally approve them. The two
--   approver roles hold an identical permission set on purpose — location versus
--   global reach is a property of role_assignments.scope_type, not of
--   role_permissions, so it cannot be expressed by granting different rows here.
--   INVENTORY_CONTROLLER alone also holds inventory:adjustment:override, the
--   negative-stock escape hatch ScrapServiceImpl checks, because only a
--   globally scoped approver should drive on-hand below zero.
-- * SHOP_MANAGER holds the shop surface its V3 description names (locations,
--   bays, schedules, technicians) plus invoice:finalize:override (#1374). It has
--   no audit grant because the shop domain defines no audit permission; add one
--   to pos-shop-manager's manifest first if that capability is wanted.
-- * SECURITY_ADMIN and READ_ONLY_SCHEDULER are NOT granted here and no longer
--   exist: V3 created them as unratified "Candidate Roles v0", nothing in the
--   codebase ever referenced them, and V23 deletes them (#1373).
--   SECURITY_ADMIN's described scope is covered by SYSTEM_ADMINISTRATOR.
-- * CUSTOMER and SELF_SERVICE_CUSTOMER hold the assistant entrypoints and nothing
--   else, confirmed deliberate on #1373. They are external-facing; any domain
--   grant to them is a new product decision, not a gap to be filled.
-- * Grants are additive. Nothing here deletes a row, so permissions an operator
--   granted through the role-permission admin API survive re-runs. Revoking a
--   grant therefore needs a versioned migration, which is what V23 does for the
--   two deleted candidate roles.
-- * 2026-08 ACCOUNT_MANAGER / CONTROLLER rescope (#1499/#1512, §6 of
--   docs/rbac-permission-role-audit-2026-08.md, decided 2026-08-25):
--   ACCOUNT_MANAGER is now a customer-accounts (AR) role -- payments, customer
--   credits, credit memos, invoicing/billing, tax exemptions, and it retains
--   reporting:view:financial-statements. CONTROLLER (created by V24) is the
--   accounting-management role -- GL configuration, journal entries, chart of
--   accounts, the close cycle, reconciliation, AP and exports -- and holds the
--   accounting-management codes ACCOUNT_MANAGER used to hold, revoked from
--   ACCOUNT_MANAGER by V25 in the same change. accounting:ap:approve,
--   accounting:ap:reject and the accounting:mapping:* family are retired
--   (superseded by accounting:ap:pay and the gl-mapping/mapping-key/
--   default-mapping families, §3) and are not granted to any role.
-- * workorder:start / workorder:workorder:start split-brain (#1499/#1512, §2
--   finding 1 / §7 task 2 of docs/rbac-permission-role-audit-2026-08.md): the
--   start endpoint enforced workorder:start while the detail-response
--   capability flag checked workorder:workorder:start, so a technician could
--   start a workorder while the UI reported they couldn't. workorder:start is
--   retired; workorder:workorder:start (already ADMIN's) is now also granted to
--   LOCATION_MANAGER and TECHNICIAN, and V26 removes the workorder:start
--   grants. The workorder:start permission definition and bit (284) stay
--   forever, per the retirement convention — only the grants retire.
-- * shop:location:*/shop:bay:view/create/edit superseded by the location:*
--   family (§3 of the audit doc): pos-shop-manager enforces none of
--   shop:location:view/create/edit/deactivate or shop:bay:view/create/edit;
--   pos-location enforces location:read/write and location:bay:read/manage
--   instead. DISPATCHER, LOCATION_MANAGER, SERVICE_ADVISOR and SHOP_MANAGER
--   are re-pointed to location:read/location:bay:read (mirroring their old
--   shop:location:view/shop:bay:view), and LOCATION_MANAGER additionally to
--   location:write/location:bay:manage (mirroring its old shop:location:
--   create/edit and shop:bay:create/edit); ADMIN already held the full
