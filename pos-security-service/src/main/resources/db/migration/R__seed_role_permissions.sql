-- * 2026-08 §2 decisions 1-5 (docs/rbac-permission-role-audit-2026-08.md,
--   decided 2026-08-25) -- previously-unwired feature areas, purely additive,
--   no revocations:
--   - Marketing (all 9 codes: campaigns, templates, stats) -> ACCOUNT_MANAGER,
